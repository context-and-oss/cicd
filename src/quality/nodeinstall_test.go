// The detection table. Every row that picks a manager names the lockfile it
// froze to; every row that refuses says why in words a consumer can act on.
func TestDetectNodePackageManager(t *testing.T) {
	cases := []struct {
		name     string
		pkg      string
		entries  []string
		yarnLock string
		want     nodePM
		warn     []string // substrings, one per expected warning, in order
		err      string
	}{
		{name: "no package.json, no lockfile: npm as before", want: npmDefault},
		{name: "npm lockfile", pkg: `{}`, entries: []string{"package.json", "package-lock.json"},
			want: nodePM{name: "npm", lockfile: "package-lock.json"}},
		{name: "npm shrinkwrap", pkg: `{}`, entries: []string{"npm-shrinkwrap.json"},
			want: nodePM{name: "npm", lockfile: "npm-shrinkwrap.json"}},
		{name: "package.json with no lockfile resolves afresh, and says so", pkg: `{}`,
			want: npmDefault, warn: []string{"no lockfile: npm install resolved"}},
		{name: "pnpm by lockfile alone: corepack chose the version", pkg: `{}`, entries: []string{"pnpm-lock.yaml"},
			want: nodePM{name: "pnpm", lockfile: "pnpm-lock.yaml"}, warn: []string{"pnpm version chosen by corepack"}},
		{name: "pnpm declared and pinned: no warning", pkg: pinnedPnpm, entries: []string{"pnpm-lock.yaml", "pnpm-workspace.yaml"},
			want: nodePM{name: "pnpm", version: "11.19.0", pinned: true, lockfile: "pnpm-lock.yaml"}},
		{name: "pnpm declared without hash is unpinned", pkg: `{"packageManager":"pnpm@9.15.0"}`, entries: []string{"pnpm-lock.yaml"},
			want: nodePM{name: "pnpm", version: "9.15.0", lockfile: "pnpm-lock.yaml"}, warn: []string{"pnpm@9.15.0 from packageManager is unpinned"}},
		{name: "declared manager wins, the other lockfile is named as ignored", pkg: pinnedPnpm,
			entries: []string{"package-lock.json", "pnpm-lock.yaml"},
			want:    nodePM{name: "pnpm", version: "11.19.0", pinned: true, lockfile: "pnpm-lock.yaml"},
			warn:    []string{"package-lock.json is ignored: packageManager declares pnpm"}},
		{name: "declared manager with no lockfile of its own but another's", pkg: pinnedPnpm,
			entries: []string{"package-lock.json"}, err: "declares packageManager pnpm@11.19.0 but the only lockfile is package-lock.json"},
		{name: "declared pnpm, no lockfile at all", pkg: pinnedPnpm,
			want: nodePM{name: "pnpm", version: "11.19.0", pinned: true}, warn: []string{"no lockfile: pnpm install resolved"}},
		{name: "two lockfiles, nothing declared", pkg: `{}`, entries: []string{"yarn.lock", "package-lock.json"},
			err: "lockfiles from more than one package manager (package-lock.json, yarn.lock)"},
		{name: "a directory named like a lockfile is not one", pkg: `{}`, entries: []string{"pnpm-lock.yaml/", "package-lock.json"},
			want: nodePM{name: "npm", lockfile: "package-lock.json"}},
		{name: "yarn classic by lockfile", pkg: `{}`, entries: []string{"yarn.lock"}, yarnLock: classicLock,
			want: nodePM{name: "yarn", lockfile: "yarn.lock"}, warn: []string{"yarn version chosen by corepack"}},
		{name: "yarn berry declared", pkg: `{"packageManager":"yarn@4.9.1+sha224.deadbeef"}`, entries: []string{"yarn.lock"}, yarnLock: berryLock,
			want: nodePM{name: "yarn", berry: true, version: "4.9.1", pinned: true, lockfile: "yarn.lock"}},
		{name: "yarn berry lockfile, nothing declared", pkg: `{}`, entries: []string{"yarn.lock"}, yarnLock: berryLock,
			err: "yarn.lock is a yarn 2+ lockfile and package.json declares no packageManager"},
		{name: "yarn 4 declared over a classic lockfile", pkg: `{"packageManager":"yarn@4.9.1"}`, entries: []string{"yarn.lock"}, yarnLock: classicLock,
			err: "declares yarn@4.9.1 but yarn.lock is a yarn 1 lockfile"},
		{name: "yarn 1 declared over a berry lockfile", pkg: `{"packageManager":"yarn@1.22.22"}`, entries: []string{"yarn.lock"}, yarnLock: berryLock,
			err: "declares yarn@1.22.22 but yarn.lock is a yarn 2+ lockfile"},
		{name: "yarn.lock with neither marker", pkg: `{}`, entries: []string{"yarn.lock"}, yarnLock: "garbage\n",
			err: "yarn.lock is neither a yarn 1 lockfile"},
		{name: "bun lockfile", pkg: `{}`, entries: []string{"bun.lockb"}, err: "installed with bun (bun.lockb)"},
		{name: "bun declared", pkg: `{"packageManager":"bun@1.2.0"}`, err: "installed with bun (packageManager bun@1.2.0)"},
		{name: "an unknown manager", pkg: `{"packageManager":"deno@2.0.0"}`, err: `packageManager names "deno"`},
		{name: "packageManager is not a string", pkg: `{"packageManager":{"name":"pnpm"}}`, err: "packageManager is not a string"},
		{name: "packageManager without a version", pkg: `{"packageManager":"pnpm"}`, err: `packageManager "pnpm" is not name@version[+hash]`},
		{name: "package.json is not JSON", pkg: `{"name":`, err: "package.json is not a JSON object"},
		{name: "declared npm version is not enforced", pkg: `{"packageManager":"npm@10.9.0"}`, entries: []string{"package-lock.json"},
			want: nodePM{name: "npm", version: "10.9.0", lockfile: "package-lock.json"}, warn: []string{"declares npm@10.9.0, which cicd does not install"}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, warnings, err := detectNodePackageManager(c.pkg, c.entries, c.yarnLock)
			if c.err != "" {
				if err == nil || !strings.Contains(err.Error(), c.err) {
					t.Fatalf("err = %v, want one containing %q", err, c.err)
				}
				return
			}
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if got != c.want {
				t.Errorf("pm = %+v, want %+v", got, c.want)
			}
			if len(warnings) != len(c.warn) {
				t.Fatalf("warnings = %q, want %d matching %q", warnings, len(c.warn), c.warn)
			}
			for i, w := range c.warn {
				if !strings.Contains(warnings[i], w) {
					t.Errorf("warning %d = %q, want it to contain %q", i, warnings[i], w)
				}
			}
		})
	}
}

// Every install is frozen to its lockfile when there is one, runs no
// lifecycle script, and records its exit whatever happens.
func TestNodeInstallLines(t *testing.T) {
	cases := []struct {
		pm    nodePM
		cmd   string
		label string
	}{
		{npmDefault, "npm install --ignore-scripts", "npm install"},
		{nodePM{name: "npm", lockfile: "package-lock.json"}, "npm ci --ignore-scripts", "npm ci"},
		{nodePM{name: "pnpm", lockfile: "pnpm-lock.yaml"}, "pnpm install --frozen-lockfile --ignore-scripts", "pnpm install"},
		{nodePM{name: "pnpm"}, "pnpm install --ignore-scripts", "pnpm install"},
		{nodePM{name: "yarn", lockfile: "yarn.lock"}, "yarn install --frozen-lockfile --ignore-scripts", "yarn install"},
		{nodePM{name: "yarn", berry: true, lockfile: "yarn.lock"}, "YARN_ENABLE_SCRIPTS=false yarn install --immutable", "yarn install"},
		{nodePM{name: "yarn", berry: true}, "YARN_ENABLE_SCRIPTS=false yarn install", "yarn install"},
	}
	for _, c := range cases {
		line := c.pm.installLine()
		if !strings.Contains(line, "{ ") || !strings.Contains(line, c.cmd+"; } >/dev/null 2>&1; echo $? > "+nodeInstallExitPath) {
			t.Errorf("%+v: install line %q does not run %q and record its exit", c.pm, line, c.cmd)
		}
		corepack := strings.Contains(line, "export COREPACK_ENABLE_DOWNLOAD_PROMPT=0; corepack enable && ")
		if corepack != (c.pm.name != "npm") {
			t.Errorf("%+v: corepack in the recorded install = %v, want %v", c.pm, corepack, c.pm.name != "npm")
		}
		if got := c.pm.installLabel(); got != c.label {
			t.Errorf("%+v: label %q, want %q", c.pm, got, c.label)
		}
		if strings.Contains(line, "--ignore-scripts") == strings.Contains(line, "YARN_ENABLE_SCRIPTS=false") {
			t.Errorf("%+v: exactly one script switch expected in %q", c.pm, line)
		}
	}
}

// Under Plug'n'Play nothing resolves outside yarn, so a berry project never
// sees npx or a bare node; everything else never sees yarn run a binary.
func TestNodeExecForms(t *testing.T) {
	berry := nodePM{name: "yarn", berry: true, lockfile: "yarn.lock"}
	pnpm := nodePM{name: "pnpm", lockfile: "pnpm-lock.yaml"}
	for _, s := range []string{eslintScript(berry, true), vitestScript(berry)} {
		if strings.Contains(s, "npx") || strings.Contains(s, "; node ") || strings.HasPrefix(s, "node ") {
			t.Errorf("berry script reaches outside yarn:\n%s", s)
		}
	}
	if s := vitestScript(berry); !strings.Contains(s, `yarn node -p "require('vitest/package.json').version"`) ||
		!strings.Contains(s, "yarn vitest run --coverage") {
		t.Errorf("berry vitest script does not resolve through yarn:\n%s", s)
	}
	for _, s := range []string{eslintScript(pnpm, true), vitestScript(pnpm)} {
		if strings.Count(s, "npm install") != strings.Count(s, "pnpm install") || strings.Contains(s, "npm ls") || strings.Contains(s, "yarn ") {
			t.Errorf("pnpm script runs another manager:\n%s", s)
		}
	}
}

// cicd adds the coverage provider only to an npm install. pnpm and yarn would
// rewrite the lockfile — or fail a frozen install — so they get a resolution
// check and their own sentinel word.
func TestVitestScriptAddsAProviderOnlyForNpm(t *testing.T) {
	npm := vitestScript(nodePM{name: "npm", lockfile: "package-lock.json"})
	if !strings.Contains(npm, "npm install --no-save") || !strings.Contains(npm, covProviderMissing) {
		t.Errorf("npm script lost its provider fetch:\n%s", npm)
	}
	for _, pm := range []nodePM{{name: "pnpm", lockfile: "pnpm-lock.yaml"}, {name: "yarn", lockfile: "yarn.lock"}, {name: "yarn", berry: true, lockfile: "yarn.lock"}} {
		s := vitestScript(pm)
		if strings.Contains(s, "--no-save") || strings.Contains(s, " add ") {
			t.Errorf("%+v: script adds a package:\n%s", pm, s)
		}
		if !strings.Contains(s, "require.resolve('@vitest/coverage-v8/package.json')") || !strings.Contains(s, covProviderUndeclared) {
			t.Errorf("%+v: script does not check for a declared provider:\n%s", pm, s)
		}
	}
	if w := coverageProviderWarning(covProviderUndeclared, nil, false, true); !strings.Contains(w, "does not declare @vitest/coverage-v8") {
		t.Errorf("undeclared provider warning = %q", w)
	}
}

