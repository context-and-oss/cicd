// The install record names the command the consumer would type, and the
// remedy for a corepack-managed install names the fetch npm never makes.
func TestInstallRecordMessages(t *testing.T) {
	pnpm := nodePM{name: "pnpm", lockfile: "pnpm-lock.yaml"}
	_, _, msg := foldEslintRun("127", eslintMissingStderr, "", "", pnpm.record("1\n"))
	for _, want := range []string{"pnpm install exited 1", "corepack unable to fetch pnpm itself from registry.npmjs.org"} {
		if !strings.Contains(msg, want) {
			t.Errorf("pnpm install failure %q does not contain %q", msg, want)
		}
	}
	ci := nodePM{name: "npm", lockfile: "package-lock.json"}
	leg := vitestNonRun(foldTestLeg("vitest", "vitest: ", nil, "/o", nil, "/e", "1\n"), false, ci.record("1\n"), "\n", true)
	if !strings.Contains(leg.err, "npm ci exited 1") || strings.Contains(leg.err, "corepack") {
		t.Errorf("npm ci failure = %q", leg.err)
	}
	if (installRecord{}).known() || (installRecord{exit: "x"}).known() {
		t.Error("an empty or unparseable exit must be unknown, never a success")
	}
}

// The token is configured for npm and for pnpm, both to the feed's host only,
// and it is bound under a name a shell keeps. pnpm 11 reads no NPM_CONFIG_*
// registry (measured), so npm's names alone would silently leave a pnpm install
// on the public registry.
func TestNodeFeedConfig(t *testing.T) {
	f := nodeFeedConfig("pkgs.example.com/feed/npm/registry/", "")
	want := map[string]string{
		"NPM_CONFIG_REGISTRY":    "https://pkgs.example.com/feed/npm/registry/",
		"PNPM_CONFIG_REGISTRY":   "https://pkgs.example.com/feed/npm/registry/",
		"NPM_CONFIG_USERCONFIG":  npmFeedUserconfig,
		"PNPM_CONFIG_USERCONFIG": npmFeedUserconfig,
	}
	if len(f.env) != len(want) {
		t.Fatalf("env = %q", f.env)
	}
	for _, kv := range f.env {
		if want[kv[0]] != kv[1] {
			t.Errorf("%s = %q, want %q", kv[0], kv[1], want[kv[0]])
		}
	}
	if f.npmrcPath != npmFeedUserconfig {
		t.Errorf("npmrc path = %q, want %q", f.npmrcPath, npmFeedUserconfig)
	}
	if got, want := f.npmrc, "//pkgs.example.com/feed/npm/registry/:_authToken=${CICD_NPM_FEED_TOKEN}\n"; got != want {
		t.Errorf("npmrc = %q, want %q", got, want)
	}
	// Every name cicd binds must survive `sh -c`: dash drops a variable whose
	// name is not a shell identifier, which is the bug this shape replaced.
	ident := regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	for _, kv := range append(f.env, [2]string{f.secretVar, ""}) {
		if !ident.MatchString(kv[0]) {
			t.Errorf("%q is not a shell identifier: dash would drop it before npm starts", kv[0])
		}
	}
	if f.secretVar != npmFeedTokenVar || !strings.Contains(f.npmrc, "${"+f.secretVar+"}") {
		t.Errorf("npmrc %q does not reference the secret variable %q", f.npmrc, f.secretVar)
	}
	if w := nodeFeedWarning(nodePM{name: "yarn", berry: true}, true); !strings.Contains(w, "not applied to this yarn install") {
		t.Errorf("yarn feed warning = %q", w)
	}
	for _, pm := range []nodePM{npmDefault, {name: "pnpm"}} {
		if w := nodeFeedWarning(pm, true); w != "" {
			t.Errorf("%s got a feed warning: %q", pm.name, w)
		}
	}
	if w := nodeFeedWarning(nodePM{name: "yarn"}, false); w != "" {
		t.Errorf("no feed, yet a warning: %q", w)
	}
}

// Every script variant the Node legs can run must at least parse: a quoting
// slip in a message or a flag turns into a shell syntax error, which the legs
// read as a missing binary or a dead install. sh -n reads without running.
func TestNodeScriptsParse(t *testing.T) {
	sh, err := exec.LookPath("sh")
	if err != nil {
		t.Skip("no sh on PATH")
	}
	pms := []nodePM{npmDefault, {name: "npm", lockfile: "package-lock.json"}, {name: "pnpm", lockfile: "pnpm-lock.yaml"},
		{name: "pnpm"}, {name: "yarn", lockfile: "yarn.lock"}, {name: "yarn", berry: true, lockfile: "yarn.lock"}, {name: "yarn", berry: true}}
	for _, pm := range pms {
		for _, s := range []string{eslintScript(pm, true), eslintScript(pm, false), vitestScript(pm)} {
			if out, err := exec.Command(sh, "-n", "-c", s).CombinedOutput(); err != nil {
				t.Errorf("%+v: script does not parse: %v\n%s\n%s", pm, err, out, s)
			}
		}
	}
}

// npmrc routing binds the same token to the same host and sets no registry:
// the project's .npmrc decides which packages reach the feed. A registry
// variable left behind would send every public package to a feed that cannot
// serve it, which is the failure this mode exists to avoid.
func TestNodeFeedConfigNpmrcRoutingBindsTheTokenOnly(t *testing.T) {
	reg := nodeFeedConfig("https://npm.feed.example/", "registry")
	f := nodeFeedConfig("https://npm.feed.example/", "npmrc")
	for _, kv := range f.env {
		if strings.HasSuffix(kv[0], "_REGISTRY") {
			t.Errorf("npmrc routing set %s, want no registry variables", kv[0])
		}
	}
	n := 0
	for _, kv := range reg.env {
		if strings.HasSuffix(kv[0], "_REGISTRY") {
			n++
		}
	}
	if n != 2 {
		t.Errorf("registry routing env = %q, want both registry variables", reg.env)
	}
	const want = "//npm.feed.example/:_authToken=${CICD_NPM_FEED_TOKEN}\n"
	if f.npmrc != want || reg.npmrc != want {
		t.Errorf("npmrc = %q (registry %q), want %q", f.npmrc, reg.npmrc, want)
	}
}

func TestNodeFeedShadowWarning(t *testing.T) {
	const feed = "https://npm.feed.example/team/"
	cases := []struct {
		name, npmrc string
		pm          nodePM
		want        bool
	}{
		{name: "no file", npmrc: ""},
		{name: "routing only", npmrc: "@example-org:registry=https://npm.feed.example/team/\n"},
		{name: "commented token", npmrc: "# //npm.feed.example/team/:_authToken=${NODE_AUTH_TOKEN}\n"},
		{name: "token for the feed", npmrc: "//npm.feed.example/team/:_authToken=${NODE_AUTH_TOKEN}\n", want: true},
		{name: "token for the feed, spaced", npmrc: "  //npm.feed.example/team/:_authToken = x\r\n", want: true},
		{name: "credential below the feed", npmrc: "//npm.feed.example/team/sub/:_auth=x\n", want: true},
		// The less specific dart loses to cicd's, and a non-token credential on
		// the same dart loses to its token: npm reads the token first.
		{name: "token for the host only", npmrc: "//npm.feed.example/:_authToken=x\n"},
		{name: "basic auth on the same dart", npmrc: "//npm.feed.example/team/:_auth=x\n"},
		{name: "other host", npmrc: "//other.example/team/:_authToken=x\n"},
		{name: "yarn is warned elsewhere", npmrc: "//npm.feed.example/team/:_authToken=x\n", pm: nodePM{name: "yarn"}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			pm := c.pm
			if pm.name == "" {
				pm = npmDefault
			}
			w := nodeFeedShadowWarning(pm, feed, c.npmrc)
			if (w != "") != c.want {
				t.Fatalf("warning = %q, want warned=%v", w, c.want)
			}
			if w != "" && strings.Contains(w, "x\n") {
				t.Errorf("warning echoes the credential value: %q", w)
			}
		})
	}
}

func TestNpmrcRoutesTo(t *testing.T) {
	const feed = "https://npm.feed.example/"
	cases := []struct {
		name, npmrc string
		want        bool
	}{
		{name: "no file", npmrc: "", want: false},
		{name: "scoped line", npmrc: "@example-org:registry=https://npm.feed.example\n", want: true},
		{name: "scoped line, no scheme, crlf", npmrc: "@example-org:registry = //npm.feed.example/\r\n", want: true},
		{name: "quoted value", npmrc: `@example-org:registry="https://npm.feed.example/"`, want: true},
		{name: "whole registry", npmrc: "registry=https://npm.feed.example/", want: true},
		{name: "variable value", npmrc: "@example-org:registry=${FEED_URL}", want: true},
		{name: "other host", npmrc: "@example-org:registry=https://other.example/", want: false},
		{name: "path below the feed", npmrc: "@example-org:registry=https://npm.feed.example/sub/", want: true},
		{name: "host that only shares a prefix", npmrc: "@example-org:registry=https://npm.feed.example.net/", want: false},
		{name: "commented out", npmrc: "# @example-org:registry=https://npm.feed.example/\n; registry=https://npm.feed.example/", want: false},
		{name: "token line is not routing", npmrc: "//npm.feed.example/:_authToken=${TOKEN}", want: false},
	}
	for _, c := range cases {
		if got := npmrcRoutesTo(c.npmrc, feed); got != c.want {
			t.Errorf("%s: npmrcRoutesTo(%q) = %v, want %v", c.name, c.npmrc, got, c.want)
		}
	}
}

// A feed with a path only covers registries at or below that path, the way
// npm only sends a path-scoped token there.
func TestNpmrcRoutesToFeedWithAPath(t *testing.T) {
	const feed = "https://host.example/org/npm/"
	if !npmrcRoutesTo("@example-org:registry=https://host.example/org/npm/", feed) {
		t.Error("the feed path itself must count as routed")
	}
	if npmrcRoutesTo("@example-org:registry=https://host.example/", feed) {
		t.Error("a registry above the feed path is not where the token applies")
	}
	if npmrcRoutesTo("@example-org:registry=https://host.example/org/npmx/", feed) {
		t.Error("a sibling path that only shares a prefix must not count")
	}
}

func TestNodeFeedRoutingWarning(t *testing.T) {
	const feed = "https://npm.feed.example/"
	if w := nodeFeedRoutingWarning(npmDefault, "npmrc", feed, ""); !strings.Contains(w, "routes no registry to the private feed") {
		t.Errorf("npmrc routing with no .npmrc: warning = %q", w)
	}
	if w := nodeFeedRoutingWarning(nodePM{name: "pnpm"}, "npmrc", feed, "@example-org:registry="+feed); w != "" {
		t.Errorf("routed .npmrc still warned: %q", w)
	}
	for _, routing := range []string{"", "registry"} {
		if w := nodeFeedRoutingWarning(npmDefault, routing, feed, ""); w != "" {
			t.Errorf("routing %q warned: %q", routing, w)
		}
	}
	// yarn already gets nodeFeedWarning: the credential is not applied at all.
	if w := nodeFeedRoutingWarning(nodePM{name: "yarn"}, "npmrc", feed, ""); w != "" {
		t.Errorf("yarn got a routing warning on top of the unapplied-credential one: %q", w)
	}
}
