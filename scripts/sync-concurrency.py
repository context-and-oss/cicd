#!/usr/bin/env python3
"""Generate module copies of the bounded scheduler; checked by check-surface."""
import pathlib
import sys

source = pathlib.Path(sys.argv[1]).read_text()
if not source.startswith("package concurrency\n"):
    sys.exit("expected package concurrency")
print("// Code generated by scripts/sync-concurrency.py; DO NOT EDIT.")
print(source.replace("package concurrency\n", "package main\n", 1), end="")
