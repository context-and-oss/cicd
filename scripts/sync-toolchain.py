#!/usr/bin/env python3
"""
Transform src/internal/detect/toolchain.go into a module-local toolchain.go.

Dagger modules are isolated, so the ADR-004 toolchain resolver is shared by file
copy. The module copies differ from the canonical internal package in exactly
two ways:

  1. `package main` (not `package detect`), with a comment saying where the
     original lives.
  2. The Language type and its constants, which the canonical file gets from
     src/internal/detect/detect.go, are inlined.

Everything else is carried verbatim, which is why this is a generator rather
than a diff to maintain by hand.

Why a generator and not just a byte-equality check between the two copies:
equality between copies cannot see the drift that actually happens. Edit the
canonical file and forget both copies, and the two copies stay byte-identical to
each other while disagreeing with the implementation they are copies of — the
check passes and says nothing. That is the `.slnx` failure (missing from two of
its three marker lists for as long as nothing compared them) with the comparison
pointed at the wrong pair. Regenerating from the canonical file and comparing is
the only form of the check that can fail in that case.

Usage:
    python3 scripts/sync-toolchain.py src/internal/detect/toolchain.go > out.go
"""
import re
import sys

HEADER = """package main

// toolchain.go is a verbatim copy of src/internal/detect/toolchain.go
// (canonical implementation — ADR-004), carried locally per the repo's
// no-shared-module rule (schema.go precedent; see CLAUDE.md). The Language
// type and constants are inlined from src/internal/detect/detect.go.
//
// Generated by scripts/sync-toolchain.py — run `make sync-toolchain` after
// editing the canonical file. Do not edit this copy directly: an edit here is
// invisible to the canonical implementation and to the other copy, and
// check-surface regenerates this file to prove it did not happen.
"""

LANGUAGE_BLOCK = """
// Language mirrors src/internal/detect.Language.
type Language string

const (
\tGo     Language = "go"
\tNode   Language = "node"
\tPython Language = "python"
\tDotnet Language = "dotnet"
)
"""


def render(canonical: str) -> str:
    if not canonical.startswith("package detect\n"):
        sys.exit("sync-toolchain: canonical file does not start with 'package detect'")

    body = canonical[len("package detect\n"):]

    # Carry the canonical import block across verbatim, then the inlined
    # Language type, then the rest. Anchoring on the block's own closing paren
    # keeps this correct as the canonical import set changes — the alternative,
    # a hardcoded import list here, is a fourth copy of the same information.
    m = re.search(r"^import \(\n(?:.*?\n)*?\)\n", body, flags=re.MULTILINE)
    if not m:
        sys.exit("sync-toolchain: could not find the canonical import block")

    imports = m.group(0)
    rest = body[m.end():].lstrip("\n")

    return HEADER + "\n" + imports + LANGUAGE_BLOCK + "\n" + rest


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__.strip())
    sys.stdout.write(render(open(sys.argv[1]).read()))
