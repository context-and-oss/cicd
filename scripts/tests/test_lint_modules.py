"""Tests for scripts/ci/lint-modules.sh.

The script is driven with a fake `go` and a fake `dagger` on PATH, so the
assertions are about what it does with their answers — which pass ran in
which state, whether a red module stops the next from being linted, and
what it exits — not about golangci-lint itself.
"""

import os
import pathlib
import re
import subprocess
import tempfile
import unittest

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "ci" / "lint-modules.sh"
CI_YML = REPO_ROOT / ".github" / "workflows" / "ci.yml"

FAKE_GO = """#!/usr/bin/env bash
# Records every invocation as "<module basename> <tags> <sdk present?>" and
# fails the default-tag pass of a module called "red".
module="$(basename "$PWD")"
tags=default
for a in "$@"; do [ "$a" = unit_test ] && tags=unit_test; done
sdk=no; [ -f dagger.gen.go ] && sdk=yes
echo "$module $tags $sdk" >> "$LINT_LOG"
if [ "$module" = red ] && [ "$tags" = default ]; then exit 1; fi
exit 0
"""

FAKE_DAGGER = """#!/usr/bin/env bash
# `dagger develop` leaves the generated SDK behind; a module called
# "nodevelop" cannot be developed.
[ "$(basename "$PWD")" = nodevelop ] && { echo "Error: failed to apply generated code: exit code: 1"; exit 1; }
echo "// Code generated by dagger. DO NOT EDIT." > dagger.gen.go
mkdir -p internal/dagger
exit 0
"""


class LintModulesTests(unittest.TestCase):
    def setUp(self):
        self.tmp = pathlib.Path(tempfile.mkdtemp())
        self.addCleanup(lambda: subprocess.run(["rm", "-rf", str(self.tmp)], check=False))
        bin_dir = self.tmp / "bin"
        bin_dir.mkdir()
        for name, body in (("go", FAKE_GO), ("dagger", FAKE_DAGGER)):
            path = bin_dir / name
            path.write_text(body)
            path.chmod(0o755)
        self.log = self.tmp / "lint.log"
        self.env = dict(os.environ, PATH=f"{bin_dir}:{os.environ['PATH']}", LINT_LOG=str(self.log))

    def module(self, name, with_sdk=False, tagged=True):
        d = self.tmp / name
        d.mkdir()
        (d / "dagger.json").write_text('{"name": "%s"}' % name)
        (d / "main.go").write_text("//go:build !unit_test\n\npackage main\n" if tagged else "package main\n")
        if tagged:
            (d / "rules_test.go").write_text("//go:build unit_test\n\npackage main\n")
        if with_sdk:
            (d / "dagger.gen.go").write_text("// stale\n")
            (d / "internal" / "dagger").mkdir(parents=True)
        return d

    def run_script(self, *dirs):
        return subprocess.run(
            ["bash", str(SCRIPT), *map(str, dirs)],
            env=self.env, capture_output=True, text=True, cwd=str(self.tmp),
        )

    def log_lines(self):
        return self.log.read_text().splitlines() if self.log.exists() else []

    def test_clean_module_is_linted_tagged_without_sdk_then_untagged_with_it(self):
        d = self.module("clean", with_sdk=True)
        res = self.run_script(d)
        self.assertEqual(res.returncode, 0, res.stderr + res.stdout)
        self.assertEqual(self.log_lines(), ["clean unit_test no", "clean default yes"])
        self.assertTrue((d / "dagger.gen.go").exists(), "develop must leave the SDK behind")
        self.assertIn("lint-modules: OK (1 module(s)", res.stdout)

    def test_a_module_with_no_tagged_file_skips_the_tagged_pass_and_says_so(self):
        # The stage orchestrators, precommit, pages and report hold one untagged
        # main.go that calls the SDK: with the SDK removed and -tags unit_test,
        # that pass can only report `undefined: dag`. It is skipped, loudly.
        d = self.module("untagged", tagged=False)
        res = self.run_script(d)
        self.assertEqual(res.returncode, 0, res.stderr + res.stdout)
        self.assertEqual(self.log_lines(), ["untagged default yes"])
        self.assertIn("untagged: no file declares the unit_test build tag; tagged pass skipped", res.stdout)

    def test_a_module_with_only_a_negative_tag_still_gets_the_tagged_pass(self):
        # `//go:build !unit_test` on the entry file is a declaration of the tag
        # set too: the tagged pass then lints the module without that file.
        d = self.module("negonly", tagged=False)
        (d / "main.go").write_text("//go:build !unit_test\n\npackage main\n")
        res = self.run_script(d)
        self.assertEqual(res.returncode, 0, res.stderr + res.stdout)
        self.assertEqual(self.log_lines(), ["negonly unit_test no", "negonly default yes"])

    def test_a_red_module_does_not_stop_the_next_and_is_named(self):
        red = self.module("red")
        clean = self.module("clean")
        res = self.run_script(red, clean)
        self.assertEqual(res.returncode, 1, res.stderr + res.stdout)
        self.assertEqual(
            self.log_lines(),
            ["red unit_test no", "red default yes", "clean unit_test no", "clean default yes"],
        )
        self.assertIn("red (default tag set)", res.stderr)
        self.assertNotIn("clean (", res.stderr)

    def test_a_failed_develop_is_red_and_skips_only_the_untagged_pass(self):
        d = self.module("nodevelop")
        res = self.run_script(d)
        self.assertEqual(res.returncode, 1, res.stderr + res.stdout)
        self.assertEqual(self.log_lines(), ["nodevelop unit_test no"])
        self.assertIn("nodevelop (dagger develop failed", res.stderr)

    def test_a_directory_without_dagger_json_is_exit_2_before_anything_runs(self):
        clean = self.module("clean")
        not_a_module = self.tmp / "docs"
        not_a_module.mkdir()
        res = self.run_script(clean, not_a_module)
        self.assertEqual(res.returncode, 2, res.stderr + res.stdout)
        self.assertIn("not a Dagger module", res.stderr)
        self.assertEqual(self.log_lines(), [], "nothing is linted once the list is unusable")

    def test_golangci_version_matches_the_lint_repo_step(self):
        script_version = re.search(r'^GOLANGCI_LINT_VERSION="(v[^"]+)"', SCRIPT.read_text(), re.M)
        self.assertIsNotNone(script_version, "the script no longer pins a version")
        ci_versions = set(re.findall(r"golangci-lint/v2/cmd/golangci-lint@(v[0-9][^ \n]*)", CI_YML.read_text()))
        self.assertEqual(ci_versions, {script_version.group(1)},
                         "src/internal and the Dagger modules must be linted by the same golangci-lint")


if __name__ == "__main__":
    unittest.main()
